// Builds the LifeOS Bookmarks extension into extension/dist for a fixed list of LifeOS origins.
//   node scripts/build-extension.mjs                          -> http://localhost:3000 only
//   node scripts/build-extension.mjs --origin https://app.example.com [--origin ...]
// The same origin list becomes the content-script match patterns and the runtime allowlist (config.js).
import { copyFileSync, mkdirSync, readdirSync, rmSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

export const EXTENSION_VERSION = '0.1.0'
const LOCAL_HOSTS = new Set(['localhost', '127.0.0.1'])

/** Returns the normalised origin, or throws. https everywhere; plain http only for localhost development. */
export function validateOrigin(input) {
  let url
  try {
    url = new URL(input)
  } catch {
    throw new Error(`Not a valid origin: ${input}`)
  }
  if (url.origin === 'null' || `${url.origin}` !== input.replace(/\/$/, '')) throw new Error(`Give an origin only (scheme, host, optional port), no path: ${input}`)
  if (url.username || url.password) throw new Error(`Origins must not contain credentials: ${input}`)
  if (url.protocol === 'http:' && !LOCAL_HOSTS.has(url.hostname)) throw new Error(`Use https for non-local origins: ${input}`)
  if (url.protocol !== 'https:' && url.protocol !== 'http:') throw new Error(`Unsupported scheme: ${input}`)
  if (url.hostname.includes('*')) throw new Error(`Wildcards are not allowed: ${input}`)
  return url.origin
}

export function buildManifest(origins) {
  return {
    manifest_version: 3,
    name: 'LifeOS Bookmarks',
    version: EXTENSION_VERSION,
    description: 'Send the Chrome bookmark folders you choose to your LifeOS library for review. Read-only.',
    minimum_chrome_version: '116',
    permissions: ['storage'],
    optional_permissions: ['bookmarks'],
    background: { service_worker: 'background.js' },
    action: { default_popup: 'popup.html', default_title: 'LifeOS Bookmarks' },
    content_scripts: [{
      matches: origins.map((origin) => `${origin}/*`),
      js: ['config.js', 'lib.js', 'content.js'],
      run_at: 'document_idle',
      all_frames: false,
    }],
    content_security_policy: { extension_pages: "script-src 'self'; object-src 'self'" },
  }
}

export function buildConfig(origins) {
  return `// Generated by scripts/build-extension.mjs. Do not edit.\nglobalThis.LIFEOS_CONFIG = Object.freeze({ allowedOrigins: Object.freeze(${JSON.stringify(origins)}) })\n`
}

export function parseArgs(argv) {
  const origins = []
  for (let i = 0; i < argv.length; i += 1) {
    if (argv[i] === '--origin' && argv[i + 1]) origins.push(validateOrigin(argv[++i]))
    else throw new Error(`Unknown argument: ${argv[i]}`)
  }
  return [...new Set(origins.length ? origins : ['http://localhost:3000'])]
}

function main() {
  const root = join(dirname(fileURLToPath(import.meta.url)), '..', 'extension')
  const origins = parseArgs(process.argv.slice(2))
  const out = join(root, 'dist')
  rmSync(out, { recursive: true, force: true })
  mkdirSync(out, { recursive: true })
  for (const file of readdirSync(join(root, 'src'))) copyFileSync(join(root, 'src', file), join(out, file))
  writeFileSync(join(out, 'manifest.json'), `${JSON.stringify(buildManifest(origins), null, 2)}\n`)
  writeFileSync(join(out, 'config.js'), buildConfig(origins))
  console.log(`Built extension/dist for: ${origins.join(', ')}`)
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) main()
